//==============================================================================
// 포함 모듈 목록.
//==============================================================================
const System = globalThis;
import { Object } from "../../dom.js/import.js";


//==============================================================================
// 등장인물.
// - 상황극에 등장하는 인물의 기본 스탯과 현재 상태를 보관한다.
// - 1차 능력치: 힘 / 민첩 / 지능 / 운.
// - 자원: 체력 / 기력 / 마력 (각각 현재값과 최대값을 별도 보유).
// - 상태: 정상 / 질병 / 중독 등 복수 보유 가능한 문자열 배열.
// - Persona 와는 독립적인 개념(Persona = 정체성, Character = 스탯/상태)이다.
//==============================================================================
export class Character extends Object {
	//==============================================================================
	// 상태 상수 목록.
	//==============================================================================
	/** @type { string } */ static STATUS_NORMAL = "정상";
	/** @type { string } */ static STATUS_ILLNESS = "질병";
	/** @type { string } */ static STATUS_POISONED = "중독";

	//==============================================================================
	// 멤버 변수 목록.
	//==============================================================================
	/** @private @type { string } */ #name;
	/** @private @type { number } */ #strength;
	/** @private @type { number } */ #dexterity;
	/** @private @type { number } */ #intelligence;
	/** @private @type { number } */ #luck;
	/** @private @type { number } */ #health;
	/** @private @type { number } */ #maxHealth;
	/** @private @type { number } */ #stamina;
	/** @private @type { number } */ #maxStamina;
	/** @private @type { number } */ #mana;
	/** @private @type { number } */ #maxMana;
	/** @private @type { Array<string> } */ #statuses;

	//==============================================================================
	// 생성.
	//==============================================================================
	/**
	 * @param { object } [options]
	 * @param { string } [options.name]
	 * @param { number } [options.strength]
	 * @param { number } [options.dexterity]
	 * @param { number } [options.intelligence]
	 * @param { number } [options.luck]
	 * @param { number } [options.health]
	 * @param { number } [options.maxHealth]
	 * @param { number } [options.stamina]
	 * @param { number } [options.maxStamina]
	 * @param { number } [options.mana]
	 * @param { number } [options.maxMana]
	 * @param { Array<string> } [options.statuses]
	 */
	constructor(options) {
		super();
		const safeOptions = options ?? {};
		this.#name = safeOptions.name ?? "";
		this.#strength = safeOptions.strength ?? 10;
		this.#dexterity = safeOptions.dexterity ?? 10;
		this.#intelligence = safeOptions.intelligence ?? 10;
		this.#luck = safeOptions.luck ?? 10;
		this.#maxHealth = safeOptions.maxHealth ?? 100;
		this.#health = safeOptions.health ?? this.#maxHealth;
		this.#maxStamina = safeOptions.maxStamina ?? 100;
		this.#stamina = safeOptions.stamina ?? this.#maxStamina;
		this.#maxMana = safeOptions.maxMana ?? 100;
		this.#mana = safeOptions.mana ?? this.#maxMana;
		const initialStatuses = safeOptions.statuses ?? [Character.STATUS_NORMAL];
		this.#statuses = initialStatuses.slice();
	}

	//==============================================================================
	// 이름 반환.
	//==============================================================================
	/**
	 * @returns { string }
	 */
	getName() {
		return this.#name;
	}

	//==============================================================================
	// 이름 설정.
	//==============================================================================
	/**
	 * @param { string } name
	 */
	setName(name) {
		this.#name = name;
	}

	//==============================================================================
	// 힘 반환.
	//==============================================================================
	/**
	 * @returns { number }
	 */
	getStrength() {
		return this.#strength;
	}

	//==============================================================================
	// 힘 설정.
	//==============================================================================
	/**
	 * @param { number } strength
	 */
	setStrength(strength) {
		this.#strength = strength;
	}

	//==============================================================================
	// 민첩 반환.
	//==============================================================================
	/**
	 * @returns { number }
	 */
	getDexterity() {
		return this.#dexterity;
	}

	//==============================================================================
	// 민첩 설정.
	//==============================================================================
	/**
	 * @param { number } dexterity
	 */
	setDexterity(dexterity) {
		this.#dexterity = dexterity;
	}

	//==============================================================================
	// 지능 반환.
	//==============================================================================
	/**
	 * @returns { number }
	 */
	getIntelligence() {
		return this.#intelligence;
	}

	//==============================================================================
	// 지능 설정.
	//==============================================================================
	/**
	 * @param { number } intelligence
	 */
	setIntelligence(intelligence) {
		this.#intelligence = intelligence;
	}

	//==============================================================================
	// 운 반환.
	//==============================================================================
	/**
	 * @returns { number }
	 */
	getLuck() {
		return this.#luck;
	}

	//==============================================================================
	// 운 설정.
	//==============================================================================
	/**
	 * @param { number } luck
	 */
	setLuck(luck) {
		this.#luck = luck;
	}

	//==============================================================================
	// 현재 체력 반환.
	//==============================================================================
	/**
	 * @returns { number }
	 */
	getHealth() {
		return this.#health;
	}

	//==============================================================================
	// 현재 체력 설정.
	//==============================================================================
	/**
	 * @param { number } health
	 */
	setHealth(health) {
		this.#health = health;
	}

	//==============================================================================
	// 최대 체력 반환.
	//==============================================================================
	/**
	 * @returns { number }
	 */
	getMaxHealth() {
		return this.#maxHealth;
	}

	//==============================================================================
	// 최대 체력 설정.
	//==============================================================================
	/**
	 * @param { number } maxHealth
	 */
	setMaxHealth(maxHealth) {
		this.#maxHealth = maxHealth;
	}

	//==============================================================================
	// 현재 기력 반환.
	//==============================================================================
	/**
	 * @returns { number }
	 */
	getStamina() {
		return this.#stamina;
	}

	//==============================================================================
	// 현재 기력 설정.
	//==============================================================================
	/**
	 * @param { number } stamina
	 */
	setStamina(stamina) {
		this.#stamina = stamina;
	}

	//==============================================================================
	// 최대 기력 반환.
	//==============================================================================
	/**
	 * @returns { number }
	 */
	getMaxStamina() {
		return this.#maxStamina;
	}

	//==============================================================================
	// 최대 기력 설정.
	//==============================================================================
	/**
	 * @param { number } maxStamina
	 */
	setMaxStamina(maxStamina) {
		this.#maxStamina = maxStamina;
	}

	//==============================================================================
	// 현재 마력 반환.
	//==============================================================================
	/**
	 * @returns { number }
	 */
	getMana() {
		return this.#mana;
	}

	//==============================================================================
	// 현재 마력 설정.
	//==============================================================================
	/**
	 * @param { number } mana
	 */
	setMana(mana) {
		this.#mana = mana;
	}

	//==============================================================================
	// 최대 마력 반환.
	//==============================================================================
	/**
	 * @returns { number }
	 */
	getMaxMana() {
		return this.#maxMana;
	}

	//==============================================================================
	// 최대 마력 설정.
	//==============================================================================
	/**
	 * @param { number } maxMana
	 */
	setMaxMana(maxMana) {
		this.#maxMana = maxMana;
	}

	//==============================================================================
	// 상태 목록 반환. (현재 보유한 모든 상태)
	//==============================================================================
	/**
	 * @returns { Array<string> }
	 */
	getStatuses() {
		return this.#statuses;
	}

	//==============================================================================
	// 상태 목록 설정. (입력 배열의 사본을 보관)
	//==============================================================================
	/**
	 * @param { Array<string> } statuses
	 */
	setStatuses(statuses) {
		this.#statuses = statuses.slice();
	}

	//==============================================================================
	// 상태 보유 여부 반환.
	//==============================================================================
	/**
	 * @param { string } status
	 * @returns { boolean }
	 */
	hasStatus(status) {
		const statuses = this.getStatuses();
		return statuses.indexOf(status) !== -1;
	}

	//==============================================================================
	// 상태 추가. (이미 보유 중이면 무시)
	//==============================================================================
	/**
	 * @param { string } status
	 */
	addStatus(status) {
		const alreadyHas = this.hasStatus(status);
		if (alreadyHas) {
			return;
		}
		this.#statuses.push(status);
	}

	//==============================================================================
	// 상태 제거. (보유하지 않은 경우 무시)
	//==============================================================================
	/**
	 * @param { string } status
	 */
	removeStatus(status) {
		const statuses = this.getStatuses();
		const statusIndex = statuses.indexOf(status);
		if (statusIndex === -1) {
			return;
		}
		this.#statuses.splice(statusIndex, 1);
	}

	//==============================================================================
	// 상태 목록 전부 비우기.
	//==============================================================================
	clearStatuses() {
		this.#statuses = [];
	}
}
