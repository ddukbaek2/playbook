const System = globalThis;
import { DomNode } from "./domnode.js";


//==============================================================================
// 화면 단위 씬.
// - SceneManager 에 의해 한 번에 하나만 활성화된다.
// - onEnter / onExit 라이프사이클을 오버라이드해서 UI 를 구성/해제한다.
//==============================================================================
export class Scene extends DomNode {
	//==============================================================================
	// 생성.
	//==============================================================================
	/**
	 * @constructor
	 */
	constructor() {
		super("div");
		this.setName("Scene");
		this.setStyle({
			position: "absolute",
			left: "0",
			top: "0",
			width: "100%",
			height: "100%",
			boxSizing: "border-box",
			overflow: "hidden"
		});
	}

	//==============================================================================
	// 진입 시 호출.
	//==============================================================================
	/**
	 * @virtual
	 */
	onEnter() {
	}

	//==============================================================================
	// 퇴장 시 호출.
	//==============================================================================
	/**
	 * @virtual
	 */
	onExit() {
	}
}
