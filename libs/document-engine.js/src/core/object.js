//==============================================================================
// 포함 모듈 목록.
//==============================================================================
const System = globalThis;


//==============================================================================
// 기반 오브젝트.
//==============================================================================
export class Object {
	//==============================================================================
	// 멤버 변수 목록.
	//==============================================================================
	/** @private @type { number } */ static #nextSerialNumber = 1;
	/** @private @type { string } */ #instanceId;
	/** @private @type { boolean } */ #isDestroyed;

	//==============================================================================
	// 생성.
	//==============================================================================
	/**
	 * @constructor
	 */
	constructor() {
		const serialNumber = Object.#nextSerialNumber;
		Object.#nextSerialNumber = serialNumber + 1;
		this.#instanceId = `obj-${serialNumber}`;
		this.#isDestroyed = false;
	}

	//==============================================================================
	// 파괴.
	//==============================================================================
	/**
	 * @virtual
	 */
	destroy() {
		const isDestroyed = this.isDestroyed();
		if (isDestroyed) {
			return;
		}
		this.#isDestroyed = true;
	}

	//==============================================================================
	// 동등성 비교.
	//==============================================================================
	/**
	 * @virtual
	 * @param { any } other
	 * @returns { boolean }
	 */
	equals(other) {
		if (other === null) {
			return false;
		}
		else if (this === other) {
			return true;
		}
		return false;
	}

	//==============================================================================
	// 인스턴스 고유식별자 반환.
	//==============================================================================
	/**
	 * @returns { string }
	 */
	getInstanceId() {
		return this.#instanceId;
	}

	//==============================================================================
	// 파괴 여부 반환.
	//==============================================================================
	/**
	 * @returns { boolean }
	 */
	isDestroyed() {
		return this.#isDestroyed;
	}
}
